"""Willy, the on-screen rehabilitation guide.

Willy is drawn from pre-rendered sprite layers (assets/willy/, regenerated by
tools/willy_sprites/render_sprites.py) and composited with NumPy/OpenCV. He
needs no 3D engine, so he stays visible in every view, including --no-avatars,
camera-only mode and the Streamlit page.

Willy is a companion, not a measurement: he mirrors the tracked arm angle the
analysis already produced and reacts to the session state. Nothing he shows is
fed back into counting or assessment.
"""
from dataclasses import dataclass
import json
import math
from pathlib import Path
import random
import time

import cv2
import numpy as np

ASSET_DIR = Path(__file__).resolve().parents[1] / "assets" / "willy"
ARM_STEP = 10
ARM_MAX = 160
WAVE_ELBOWS = (-40, -20, 0, 20, 40)
CALM_STATUSES = ("CALIBRATION", "SUIVI PERDU", "POSITION A AJUSTER", "EPAULES PRETES", "REPOS REQUIS")


@dataclass
class WillyPose:
    """One frame of Willy. Arm sides are screen sides: L = left of the screen."""
    arm_l: float = 0.
    arm_r: float = 0.
    wave_side: str | None = None
    wave_elbow: float = 0.
    eyes: str = "open"        # open | blink | happy
    mouth: str = "smile"      # smile | talk1 | talk2
    bob: float = 0.           # vertical offset, sprite pixels (negative = up)
    tilt: float = 0.          # head tilt, degrees


def exercise_screen_side(arm, mirror=True):
    """Willy faces the patient like a mirror: raise the arm on the patient's screen side."""
    return "R" if (arm == "right") == bool(mirror) else "L"


class WillyGuide:
    def __init__(self, asset_dir=ASSET_DIR, rng=None):
        asset_dir = Path(asset_dir)
        meta = json.loads((asset_dir / "willy.json").read_text(encoding="utf-8"))
        self.canvas_w, self.canvas_h = meta["canvas"]
        self.neck = tuple(meta["neck"])
        self.layers = {}
        for name, offset in meta["layers"].items():
            rgba = cv2.imread(str(asset_dir / f"{name}.png"), cv2.IMREAD_UNCHANGED)
            if rgba is None or rgba.shape[2] != 4:
                raise FileNotFoundError(f"Sprite de Willy illisible : {name}.png")
            rgba = cv2.cvtColor(rgba, cv2.COLOR_BGRA2RGBA).astype(np.float32) / 255.
            rgba[..., :3] *= rgba[..., 3:]  # premultiplied: cheap, halo-free compositing
            self.layers[name] = (rgba, tuple(int(v) for v in offset))
        # Crop the composed canvas to Willy's full reach so he fills his screen box.
        self.crop = self._reach_box()
        self.rng = rng or random.Random(7)
        self.pose = WillyPose()
        self._arm = {"L": 0., "R": 0.}
        self._mode = None
        self._mode_since = 0.
        self._celebrate_until = 0.
        self._celebrate_happy = True
        self._last_rep = 0
        self._blink_at = 2.
        self._mouth_next = 0.
        self._mouth = "smile"
        self._last_time = None
        self._cache_key = None
        self._cache = None

    # ------------------------------------------------------------------ state
    def update(self, analysis, mode, processor, mirror=True, speaking=False, now=None):
        """Advance Willy from the current session state; returns the pose drawn next."""
        now = time.monotonic() if now is None else now
        dt = 0. if self._last_time is None else max(0., min(.2, now - self._last_time))
        self._last_time = now
        if mode != self._mode:
            self._mode, self._mode_since = mode, now
            if mode == "finished":
                self._celebrate_until, self._celebrate_happy = now + 3., True
            if mode == "ready":
                self._last_rep = 0
        since = now - self._mode_since
        target = {"L": 0., "R": 0.}
        pose = WillyPose()
        happy = False
        wave = False
        status = getattr(analysis, "status", "")

        # A newly counted repetition: celebrate a correct one, nod for the others.
        result = getattr(processor, "last_evaluation", None)
        rep = getattr(result, "rep_index", 0) or 0
        if result is not None and rep > self._last_rep:
            self._last_rep = rep
            label = getattr(result, "status_label", "")
            if label != "INDETERMINE":
                self._celebrate_until, self._celebrate_happy = now + 1.6, bool(getattr(result, "is_correct", False))

        if mode == "ready":
            wave = (since % 7.) < 2.2
            happy = wave
        elif mode == "finished":
            happy = True
        elif mode == "running" and status not in CALM_STATUSES:
            side = exercise_screen_side(getattr(processor, "arm", "right"), mirror)
            angle = (getattr(analysis, "metrics", None) or {}).get("abduction")
            if angle is not None and math.isfinite(angle):
                target[side] = float(np.clip(angle, 0, ARM_MAX))
            phase = getattr(getattr(analysis, "phase", None), "name", "")
            hold = getattr(processor.config.timing, "min_hold_time_sec", 0) if hasattr(processor, "config") else 0
            happy = phase == "HOLD" and getattr(analysis, "hold_seconds", 0) >= hold
            cue = getattr(analysis, "cue", None)
            if getattr(getattr(cue, "level", None), "value", "") == "WARNING":
                pose.tilt = 6.

        celebrating = now < self._celebrate_until
        if celebrating and self._celebrate_happy:
            target = {"L": 150., "R": 150.}
            pose.bob = -abs(math.sin(now * 9.)) * 14.
            happy = True
        elif celebrating:  # encouraging nod, never a "sad" face
            pose.tilt = math.sin(now * 10.) * 5.

        # Arms ease toward their targets; tracked angles are already filtered upstream.
        k = 1. if dt == 0. else 1. - math.exp(-dt * 10.)
        for side in ("L", "R"):
            self._arm[side] += (target[side] - self._arm[side]) * k
        pose.arm_l, pose.arm_r = self._arm["L"], self._arm["R"]
        if wave and not celebrating:
            pose.wave_side = "R"
            pose.wave_elbow = math.sin(now * 8.) * 40.

        if not celebrating:
            pose.bob += math.sin(now * 2.) * 2.5
            pose.tilt += math.sin(now * .7) * 2.
        pose.eyes = "happy" if happy else self._blink(now)
        pose.mouth = self._talk(now) if speaking else "smile"
        self.pose = pose
        return pose

    def _blink(self, now):
        if now >= self._blink_at:
            if now - self._blink_at < .14:
                return "blink"
            self._blink_at = now + 2.5 + self.rng.random() * 2.5
        return "open"

    def _talk(self, now):
        if now >= self._mouth_next:
            self._mouth = self.rng.choice(("talk1", "talk2", "talk2", "smile", "talk1"))
            self._mouth_next = now + .07 + self.rng.random() * .08
        return self._mouth

    # ------------------------------------------------------------------ drawing
    def _arm_layer(self, side, pose):
        if pose.wave_side == side:
            elbow = min(WAVE_ELBOWS, key=lambda e: abs(e - pose.wave_elbow))
            return f"arm{side}_wave_{elbow:+03d}"
        angle = pose.arm_l if side == "L" else pose.arm_r
        step = int(round(np.clip(angle, 0, ARM_MAX) / ARM_STEP) * ARM_STEP)
        return f"arm{side}_{step:03d}"

    def _reach_box(self):
        boxes = [(x, y, x + img.shape[1], y + img.shape[0]) for img, (x, y) in self.layers.values()]
        left, top = min(b[0] for b in boxes), min(b[1] for b in boxes)
        right, bottom = max(b[2] for b in boxes), max(b[3] for b in boxes)
        pad = 18  # room for bobbing/jumping
        return max(0, left - pad), max(0, top - pad), min(self.canvas_w, right + pad), min(self.canvas_h, bottom + pad)

    def _paste(self, canvas, name, dy):
        img, (x, y) = self.layers[name]
        y += int(round(dy))
        h, w = img.shape[:2]
        y0, y1 = max(0, y), min(canvas.shape[0], y + h)
        x0, x1 = max(0, x), min(canvas.shape[1], x + w)
        if y1 <= y0 or x1 <= x0:
            return
        src = img[y0 - y:y1 - y, x0 - x:x1 - x]
        dst = canvas[y0:y1, x0:x1]
        dst *= 1. - src[..., 3:]
        dst += src

    def _paste_head(self, canvas, name, dy, tilt):
        if abs(tilt) < .2:
            self._paste(canvas, name, dy)
            return
        img, (x, y) = self.layers[name]
        nx, ny = self.neck
        # Rotate the head crop around the neck, expressed in the crop's own coordinates.
        matrix = cv2.getRotationMatrix2D((nx - x, ny - y), tilt, 1.)
        matrix[:, 2] += (x, y + dy)
        warped = cv2.warpAffine(img, matrix, (canvas.shape[1], canvas.shape[0]), flags=cv2.INTER_LINEAR,
                                borderMode=cv2.BORDER_CONSTANT, borderValue=0)
        canvas *= 1. - warped[..., 3:]
        canvas += warped

    def compose(self, pose=None):
        """Full-resolution premultiplied RGBA float image of the current pose."""
        pose = pose or self.pose
        canvas = np.zeros((self.canvas_h, self.canvas_w, 4), np.float32)
        self._shadow(canvas, pose.bob)
        self._paste(canvas, "body", pose.bob)
        self._paste_head(canvas, f"head_{pose.eyes}_{pose.mouth}", pose.bob, pose.tilt)
        self._paste(canvas, self._arm_layer("L", pose), pose.bob)
        self._paste(canvas, self._arm_layer("R", pose), pose.bob)
        left, top, right, bottom = self.crop
        return canvas[top:bottom, left:right]

    def _shadow(self, canvas, bob):
        img, (x, y) = self.layers["body"]
        feet_y = y + img.shape[0] - 6
        cx = x + img.shape[1] / 2
        lift = max(0., -bob) / 14.
        axes = (int(img.shape[1] * (.42 - .08 * lift)), 13)
        mask = np.zeros(canvas.shape[:2], np.float32)
        cv2.ellipse(mask, (int(cx), int(feet_y)), axes, 0, 0, 360, .22 * (1 - .4 * lift), -1, cv2.LINE_AA)
        mask = cv2.GaussianBlur(mask, (0, 0), 6)
        canvas[..., 3] = mask
        canvas[..., :3] = mask[..., None] * np.array((.12, .2, .2), np.float32)

    def render(self, width, height):
        """Willy fitted into width x height: straight-alpha RGBA uint8, transparent margins."""
        width, height = max(1, int(width)), max(1, int(height))
        pose = self.pose
        key = (width, height, self._arm_layer("L", pose), self._arm_layer("R", pose), pose.eyes, pose.mouth,
               round(pose.bob), round(pose.tilt, 1))
        if key == self._cache_key:
            return self._cache
        image = self.compose(pose)
        h, w = image.shape[:2]
        scale = min(width / w, height / h)
        size = (max(1, round(w * scale)), max(1, round(h * scale)))
        small = cv2.resize(image, size, interpolation=cv2.INTER_AREA if scale < 1 else cv2.INTER_CUBIC)
        out = np.zeros((height, width, 4), np.float32)
        ox, oy = (width - size[0]) // 2, height - size[1]  # stand on the bottom edge
        out[oy:oy + size[1], ox:ox + size[0]] = small
        alpha = np.clip(out[..., 3:], 0, 1)
        rgb = np.where(alpha > 1e-4, out[..., :3] / np.maximum(alpha, 1e-4), 0)
        result = (np.concatenate([np.clip(rgb, 0, 1), alpha], axis=2) * 255 + .5).astype(np.uint8)
        self._cache_key, self._cache = key, result
        return result


_shared = None


def shared_guide():
    """One Willy per process, created on first use; None if the sprites are missing."""
    global _shared
    if _shared is None:
        try:
            _shared = WillyGuide()
        except (FileNotFoundError, OSError, ValueError, KeyError) as error:
            print(f"[WILLY] Sprites indisponibles : {error}")
            _shared = False
    return _shared or None


def willy_portrait(width, height):
    """A friendly still of Willy (RGBA uint8) for pages without the live dashboard."""
    guide = shared_guide()
    if guide is None:
        return None
    guide.pose = WillyPose(eyes="happy", wave_side="R", wave_elbow=20.)
    return guide.render(width, height).copy()
