"""Willy, the on-screen rehabilitation guide.

Willy is drawn from pre-rendered sprite layers (assets/willy/, regenerated by
tools/willy_sprites/render_sprites.py) and composited with NumPy/OpenCV. He
needs no 3D engine, so he stays visible in every view, including --no-avatars,
camera-only mode and the Streamlit page.

Willy is a companion, not a measurement: he mirrors the tracked arm angle the
analysis already produced and reacts to the session state. Nothing he shows is
fed back into counting or assessment.
"""
from dataclasses import dataclass
import json
import math
from collections import OrderedDict
from pathlib import Path
import random
import time

import cv2
import numpy as np

ASSET_DIR = Path(__file__).resolve().parents[1] / "assets" / "willy"
ARM_STEP = 10
ARM_MAX = 160
WAVE_ELBOWS = (-40, -20, 0, 20, 40)
CALM_STATUSES = ("CALIBRATION", "SUIVI PERDU", "POSITION A AJUSTER", "EPAULES PRETES", "REPOS REQUIS")
# Points of Willy's body in sprite-canvas pixels, for highlights and the bubble's tail.
ANCHORS = {"head": (282., 150.), "mouth": (282., 230.), "shoulder_L": (172., 352.), "shoulder_R": (388., 352.),
           "trunk": (280., 440.), "arm_L": (100., 357.), "arm_R": (460., 357.)}
ACTS = ("wave", "idle", "point", "demo", "nod", "cheer", "calm", "mirror")
# Pointing at a zone of the screen (Phase 9.2): the arm on its side rises to its height.
POINT_MIN = 30.            # even toward something below him, the arm comes away from the body
POINT_HOLD = 4.            # seconds a point lasts with nothing to aim at (longer while speaking)
LOOK_AFTER = 140.          # sprite pixels from the head's centre beyond which he turns his head
# When nothing happens: blink every 3-6 s; after 13.5-28 quiet seconds a glance, then a stretch
# or a wave (so one of the two every 30-60 s), never the same move twice in a row.
BLINK_EVERY = (3., 6.)
IDLE_WAIT = (13.5, 28.)
IDLE_MOVES = {"glance": 1.6, "stretch": 2.4, "wave": 2.2}   # seconds each
TIMED_ACTS = {"wave": 2.6, "cheer": 1.8, "nod": 1.4, "idle": 1., "calm": 1.}


@dataclass
class WillyPose:
    """One frame of Willy. Arm sides are screen sides: L = left of the screen."""
    arm_l: float = 0.
    arm_r: float = 0.
    wave_side: str | None = None
    wave_elbow: float = 0.
    eyes: str = "open"        # open | blink | happy
    mouth: str = "smile"      # smile | talk1 | talk2
    bob: float = 0.           # vertical offset, sprite pixels (negative = up)
    tilt: float = 0.          # head tilt, degrees
    look: str | None = None   # head turned toward a screen side: "L", "R" or None (facing)


def exercise_screen_side(arm, mirror=True):
    """Willy faces the patient like a mirror: raise the arm on the patient's screen side."""
    return "R" if (arm == "right") == bool(mirror) else "L"


class WillyGuide:
    def __init__(self, asset_dir=ASSET_DIR, rng=None):
        asset_dir = Path(asset_dir)
        meta = json.loads((asset_dir / "willy.json").read_text(encoding="utf-8"))
        self.canvas_w, self.canvas_h = meta["canvas"]
        self.neck = tuple(meta["neck"])
        self.layers = {}
        for name, offset in meta["layers"].items():
            rgba = cv2.imread(str(asset_dir / f"{name}.png"), cv2.IMREAD_UNCHANGED)
            if rgba is None or rgba.shape[2] != 4:
                raise FileNotFoundError(f"Sprite de Willy illisible : {name}.png")
            rgba = cv2.cvtColor(rgba, cv2.COLOR_BGRA2RGBA).astype(np.float32) / 255.
            rgba[..., :3] *= rgba[..., 3:]  # premultiplied: cheap, halo-free compositing
            self.layers[name] = (rgba, tuple(int(v) for v in offset))
        # Crop the composed canvas to Willy's full reach so he fills his screen box.
        self.crop = self._reach_box()
        self.rng = rng or random.Random(7)
        self.pose = WillyPose()
        self._arm = {"L": 0., "R": 0.}
        self._mode = None
        self._mode_since = 0.
        self._celebrate_until = 0.
        self._celebrate_happy = True
        self._last_rep = 0
        self._blink_at, self._blink_until = 2., 0.
        self._aim = None          # (side, arm angle, head turn) toward the zone Willy talks about
        self._quiet_since = None  # last time something happened (speech, act, mode change)
        self._idle = None         # (move, start) of the idle move in progress
        self._idle_wait = None
        self._last_idle = self._last_big = None
        self._mouth_next = 0.
        self._mouth = "smile"
        self._last_time = None
        self._renders, self._render_bytes = OrderedDict(), 0  # recent renders, newest last
        # What Willy acts out for his current line (outside a running session, where he mirrors the patient).
        self._act = None
        self._act_since = 0.
        self.demo_angle = 0.     # arm angle of the "demo" act, set by the tour every frame
        self.demo_side = "R"
        self.point_side = "L"    # Willy points with the arm on the screen's left: toward the app
        self.glance_side = "L"   # where he glances when nothing happens: toward the patient's image

    def perform(self, act, now=None):
        """Start an act for the line Willy is saying: wave, idle, point, demo, nod, cheer, calm, mirror."""
        if act not in ACTS:
            act = "idle"
        self._act = None if act == "mirror" else act
        self._act_since = time.monotonic() if now is None else now
        self._quiet_since, self._idle = self._act_since, None

    def anchor(self, name, width, height):
        """Where a body point lands when Willy is rendered into width x height (bob ignored)."""
        x, y = ANCHORS[name]
        left, top, right, bottom = self.crop
        cw, ch = right - left, bottom - top
        scale = min(width / cw, height / ch)
        ox, oy = (width - round(cw * scale)) // 2, height - round(ch * scale)
        return ox + (x - left) * scale, oy + (y - top) * scale

    def _to_sprite(self, x, y, width, height):
        """The inverse of `anchor`: a point of the width x height render, in sprite pixels."""
        left, top, right, bottom = self.crop
        cw, ch = right - left, bottom - top
        scale = min(width / cw, height / ch)
        ox, oy = (width - round(cw * scale)) // 2, height - round(ch * scale)
        return (x - ox) / scale + left, (y - oy) / scale + top

    def point_at(self, target, box):
        """Aim at `target` (x, y), Willy being drawn in `box` (left, top, right, bottom), same units.

        The arm on the target's side rises to its height (higher zone, higher arm) and the head
        turns toward it. A target on Willy himself, or None, cancels the aim. Screens call this
        every frame before `update`, with the centre of the zone in the spotlight.
        """
        self._aim = None
        if target is None:
            return None
        width, height = box[2] - box[0], box[3] - box[1]
        x, y = self._to_sprite(target[0] - box[0], target[1] - box[1], width, height)
        if ANCHORS["shoulder_L"][0] <= x <= ANCHORS["shoulder_R"][0] and ANCHORS["head"][1] - 150 <= y <= self.canvas_h:
            return None  # on Willy himself
        side = "L" if x < ANCHORS["trunk"][0] else "R"
        sx, sy = ANCHORS[f"shoulder_{side}"]
        angle = math.degrees(math.atan2(abs(x - sx), y - sy))  # 0: straight down, 90: level, 180: up
        look = side if abs(x - ANCHORS["head"][0]) > LOOK_AFTER else None
        self._aim = (side, float(np.clip(angle, POINT_MIN, ARM_MAX)), look)
        return self._aim

    # ------------------------------------------------------------------ state
    def update(self, analysis, mode, processor, mirror=True, speaking=False, now=None):
        """Advance Willy from the current session state; returns the pose drawn next."""
        now = time.monotonic() if now is None else now
        dt = 0. if self._last_time is None else max(0., min(.2, now - self._last_time))
        self._last_time = now
        changed = mode != self._mode
        if changed:
            self._mode, self._mode_since = mode, now
            if mode == "finished":
                self._celebrate_until, self._celebrate_happy = now + 3., True
            if mode == "ready":
                self._last_rep = 0
        if self._quiet_since is None or changed:
            self._quiet_since, self._idle = now, None
        since = now - self._mode_since
        target = {"L": 0., "R": 0.}
        pose = WillyPose()
        happy = False
        wave = False
        status = getattr(analysis, "status", "")

        # A newly counted repetition: celebrate a correct one, nod for the others.
        result = getattr(processor, "last_evaluation", None)
        rep = getattr(result, "rep_index", 0) or 0
        if result is not None and rep > self._last_rep:
            self._last_rep = rep
            label = getattr(result, "status_label", "")
            if label != "INDETERMINE":
                self._celebrate_until, self._celebrate_happy = now + 1.6, bool(getattr(result, "is_correct", False))

        if mode == "ready":
            wave = since < 2.2  # a greeting; then the idle moves below, when nothing happens
            happy = wave
        elif mode == "finished":
            happy = True
        elif mode == "running" and status not in CALM_STATUSES:
            side = exercise_screen_side(getattr(processor, "arm", "right"), mirror)
            angle = (getattr(analysis, "metrics", None) or {}).get("abduction")
            if angle is not None and math.isfinite(angle):
                target[side] = float(np.clip(angle, 0, ARM_MAX))
            phase = getattr(getattr(analysis, "phase", None), "name", "")
            hold = getattr(processor.config.timing, "min_hold_time_sec", 0) if hasattr(processor, "config") else 0
            happy = phase == "HOLD" and getattr(analysis, "hold_seconds", 0) >= hold
            cue = getattr(analysis, "cue", None)
            if getattr(getattr(cue, "level", None), "value", "") == "WARNING":
                pose.tilt = 6.

        celebrating = now < self._celebrate_until
        if self._act is not None and mode != "running":
            target, pose, happy, wave, celebrating = self._acted(now, target, pose, speaking)
        if self._aim is not None and not celebrating:
            pose.look = self._aim[2]  # he looks at what he talks about
        busy = (bool(speaking) or celebrating or wave or mode == "running" or self._aim is not None
                or self._acting(now, speaking))
        closed = False
        idle = self._quiet(now, busy)
        if idle is not None:
            move, age = idle
            if move == "glance":
                pose.look = self.glance_side
            elif move == "wave":
                wave = happy = True
            else:  # a small stretch: both arms up, eyes closed, a little taller
                lift = min(1., age / .6, max(0., IDLE_MOVES["stretch"] - age) / .8)
                target = {"L": 140. * lift, "R": 140. * lift}
                pose.bob -= 6. * lift
                closed = lift > .8
        if celebrating and self._celebrate_happy:
            target = {"L": 150., "R": 150.}
            pose.bob = -abs(math.sin(now * 9.)) * 14.
            happy = True
        elif celebrating:  # encouraging nod, never a "sad" face
            pose.tilt = math.sin(now * 10.) * 5.

        # Arms ease toward their targets; tracked angles are already filtered upstream.
        k = 1. if dt == 0. else 1. - math.exp(-dt * 10.)
        for side in ("L", "R"):
            self._arm[side] += (target[side] - self._arm[side]) * k
        pose.arm_l, pose.arm_r = self._arm["L"], self._arm["R"]
        if wave and not celebrating:
            pose.wave_side = "R"
            pose.wave_elbow = math.sin(now * 8.) * 40.

        if not celebrating:
            pose.bob += math.sin(now * 2.) * 2.5
            pose.tilt += math.sin(now * .7) * 2.
        blink = self._blink(now)  # every frame, so the blinks keep their 3-6 s rhythm
        pose.eyes = "happy" if happy else "blink" if closed else blink
        # `speaking` is the mouth matching the voice's loudness (lip sync), or True/False
        pose.mouth = speaking if isinstance(speaking, str) else self._talk(now) if speaking else "smile"
        self.pose = pose
        return pose

    def _acted(self, now, target, pose, speaking=False):
        """Pose for the current act: (arm targets, pose, happy eyes, waving, celebrating)."""
        act, age = self._act, now - self._act_since
        target, pose = {"L": 0., "R": 0.}, WillyPose()
        happy = wave = celebrating = False
        if act == "wave":
            wave = age < 2.6
            happy = wave
        elif act == "point":
            if self._aim is not None:  # the zone in the spotlight: its side, its height
                side, angle, _ = self._aim
                target[side] = angle
            elif age < POINT_HOLD or speaking:
                target[self.point_side] = 70.
        elif act == "cheer" and age < 1.8:
            celebrating, self._celebrate_happy = True, True
            self._celebrate_until = max(self._celebrate_until, self._act_since + 1.8)
        elif act == "nod" and age < 1.4:
            pose.tilt = math.sin(age * 10.) * 6.
        elif act == "demo":
            target[self.demo_side] = float(np.clip(self.demo_angle, 0, ARM_MAX))
            happy = 80. <= self.demo_angle <= 100.
        return target, pose, happy, wave, celebrating

    def _acting(self, now, speaking):
        """Whether the current act still moves Willy (no idle move meanwhile)."""
        act = self._act
        if act is None:
            return False
        age = now - self._act_since
        if act == "demo":
            return True
        if act == "point":
            return age < POINT_HOLD or bool(speaking)
        return age < TIMED_ACTS.get(act, 1.)

    def _quiet(self, now, busy):
        """The idle move in progress, as (move, seconds since it started), or None.

        After 13.5-28 s without anything happening: a glance, then a stretch or a wave (the one
        not done last time), and so on; never the same move twice in a row.
        """
        if busy:
            self._quiet_since, self._idle = now, None
            return None
        if self._idle is not None:
            move, start = self._idle
            if now - start < IDLE_MOVES[move]:
                return move, now - start
            self._idle, self._quiet_since = None, now
        if self._idle_wait is None:
            self._idle_wait = IDLE_WAIT[0] + self.rng.random() * (IDLE_WAIT[1] - IDLE_WAIT[0])
        if now - self._quiet_since < self._idle_wait:
            return None
        if self._last_idle != "glance":
            move = "glance"
        else:
            move = {"stretch": "wave", "wave": "stretch"}.get(self._last_big) or self.rng.choice(("stretch", "wave"))
            self._last_big = move
        self._last_idle, self._idle, self._idle_wait = move, (move, now), None
        return move, 0.

    def _blink(self, now):
        """A blink of 0.14 s; the next one starts 3-6 s after this one started."""
        if now >= self._blink_at:
            self._blink_until = now + .14
            self._blink_at = now + BLINK_EVERY[0] + self.rng.random() * (BLINK_EVERY[1] - BLINK_EVERY[0])
        return "blink" if now < self._blink_until else "open"

    def _talk(self, now):
        if now >= self._mouth_next:
            self._mouth = self.rng.choice(("talk1", "talk2", "talk2", "smile", "talk1"))
            self._mouth_next = now + .07 + self.rng.random() * .08
        return self._mouth

    # ------------------------------------------------------------------ drawing
    def _head_layer(self, pose):
        name = f"head_{pose.eyes}_{pose.mouth}"
        turned = f"{name}_look{pose.look}"
        return turned if pose.look and turned in self.layers else name

    def _arm_layer(self, side, pose):
        if pose.wave_side == side:
            elbow = min(WAVE_ELBOWS, key=lambda e: abs(e - pose.wave_elbow))
            return f"arm{side}_wave_{elbow:+03d}"
        angle = pose.arm_l if side == "L" else pose.arm_r
        step = int(round(np.clip(angle, 0, ARM_MAX) / ARM_STEP) * ARM_STEP)
        return f"arm{side}_{step:03d}"

    def _reach_box(self):
        boxes = [(x, y, x + img.shape[1], y + img.shape[0]) for img, (x, y) in self.layers.values()]
        left, top = min(b[0] for b in boxes), min(b[1] for b in boxes)
        right, bottom = max(b[2] for b in boxes), max(b[3] for b in boxes)
        pad = 18  # room for bobbing/jumping
        return max(0, left - pad), max(0, top - pad), min(self.canvas_w, right + pad), min(self.canvas_h, bottom + pad)

    def _paste(self, canvas, name, dy):
        img, (x, y) = self.layers[name]
        y += int(round(dy))
        h, w = img.shape[:2]
        y0, y1 = max(0, y), min(canvas.shape[0], y + h)
        x0, x1 = max(0, x), min(canvas.shape[1], x + w)
        if y1 <= y0 or x1 <= x0:
            return
        src = img[y0 - y:y1 - y, x0 - x:x1 - x]
        dst = canvas[y0:y1, x0:x1]
        dst *= 1. - src[..., 3:]
        dst += src

    def _paste_head(self, canvas, name, dy, tilt):
        if abs(tilt) < .2:
            self._paste(canvas, name, dy)
            return
        img, (x, y) = self.layers[name]
        nx, ny = self.neck
        # Rotate the head crop around the neck, expressed in the crop's own coordinates.
        matrix = cv2.getRotationMatrix2D((nx - x, ny - y), tilt, 1.)
        matrix[:, 2] += (x, y + dy)
        warped = cv2.warpAffine(img, matrix, (canvas.shape[1], canvas.shape[0]), flags=cv2.INTER_LINEAR,
                                borderMode=cv2.BORDER_CONSTANT, borderValue=0)
        canvas *= 1. - warped[..., 3:]
        canvas += warped

    def compose(self, pose=None):
        """Full-resolution premultiplied RGBA float image of the current pose."""
        pose = pose or self.pose
        canvas = np.zeros((self.canvas_h, self.canvas_w, 4), np.float32)
        self._shadow(canvas, pose.bob)
        self._paste(canvas, "body", pose.bob)
        self._paste_head(canvas, self._head_layer(pose), pose.bob, pose.tilt)
        self._paste(canvas, self._arm_layer("L", pose), pose.bob)
        self._paste(canvas, self._arm_layer("R", pose), pose.bob)
        left, top, right, bottom = self.crop
        return canvas[top:bottom, left:right]

    def _shadow(self, canvas, bob):
        img, (x, y) = self.layers["body"]
        feet_y = y + img.shape[0] - 6
        cx = x + img.shape[1] / 2
        lift = max(0., -bob) / 14.
        axes = (int(img.shape[1] * (.42 - .08 * lift)), 13)
        mask = np.zeros(canvas.shape[:2], np.float32)
        cv2.ellipse(mask, (int(cx), int(feet_y)), axes, 0, 0, 360, .22 * (1 - .4 * lift), -1, cv2.LINE_AA)
        mask = cv2.GaussianBlur(mask, (0, 0), 6)
        canvas[..., 3] = mask
        canvas[..., :3] = mask[..., None] * np.array((.12, .2, .2), np.float32)

    def render(self, width, height):
        """Willy fitted into width x height: straight-alpha RGBA uint8, transparent margins."""
        width, height = max(1, int(width)), max(1, int(height))
        pose = self.pose
        key = (width, height, self._arm_layer("L", pose), self._arm_layer("R", pose), self._head_layer(pose),
               round(pose.bob), round(pose.tilt, 1))
        cached = self._renders.get(key)
        if cached is not None:  # blinks, talking and bobbing come back to the same few poses
            self._renders.move_to_end(key)
            return cached
        image = self.compose(pose)
        h, w = image.shape[:2]
        scale = min(width / w, height / h)
        size = (max(1, round(w * scale)), max(1, round(h * scale)))
        small = cv2.resize(image, size, interpolation=cv2.INTER_AREA if scale < 1 else cv2.INTER_CUBIC)
        # Un-premultiply only the sprite's own rectangle; the margins stay fully transparent.
        alpha = np.clip(small[..., 3:], 0, 1)
        rgb = np.where(alpha > 1e-4, small[..., :3] / np.maximum(alpha, 1e-4), 0)
        result = np.zeros((height, width, 4), np.uint8)
        ox, oy = (width - size[0]) // 2, height - size[1]  # stand on the bottom edge
        result[oy:oy + size[1], ox:ox + size[0]] = (np.concatenate([np.clip(rgb, 0, 1), alpha], axis=2) * 255 + .5).astype(np.uint8)
        self._renders[key] = result
        self._render_bytes += result.nbytes
        while self._render_bytes > RENDER_CACHE_BYTES and len(self._renders) > 1:
            _, old = self._renders.popitem(last=False)
            self._render_bytes -= old.nbytes
        return result


_shared = None
RENDER_CACHE_BYTES = 48 * 1024 * 1024  # recent Willy renders kept (about 16 big ones)


def shared_guide():
    """One Willy per process, created on first use; None if the sprites are missing."""
    global _shared
    if _shared is None:
        try:
            _shared = WillyGuide()
        except (FileNotFoundError, OSError, ValueError, KeyError) as error:
            print(f"[WILLY] Sprites indisponibles : {error}")
            _shared = False
    return _shared or None


def willy_portrait(width, height):
    """A friendly still of Willy (RGBA uint8) for pages without the live dashboard."""
    guide = shared_guide()
    if guide is None:
        return None
    guide.pose = WillyPose(eyes="happy", wave_side="R", wave_elbow=20.)
    return guide.render(width, height).copy()
